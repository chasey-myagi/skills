import { test } from "node:test";
import assert from "node:assert/strict";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { prepareReview } from "../scripts/prepare.mjs";
import { runReviewGate } from "../scripts/core.mjs";
import { sha256 } from "../scripts/schema.mjs";
import { commitRel, freshRunDir, gateReport, gitC, makeRepo, rt, sha, writeRel } from "./helpers.mjs";

const PACKAGE = dirname(dirname(fileURLToPath(import.meta.url)));
const ROOT = dirname(PACKAGE);

function diffRepo(files) {
  const repo = makeRepo();
  const base = commitRel(repo, "README.md", "base\n", "base");
  for (const [path, content] of Object.entries(files)) writeRel(repo, path, content);
  gitC(repo, ["add", "-A"]);
  gitC(repo, ["commit", "-m", "head"]);
  return { repoDir: repo, mode: "diff", base, head: sha(repo), repro: false };
}

async function promptsFor(args, runtime = {}) {
  const state = await prepareReview({ ...args, runDir: args.runDir || freshRunDir() }, runtime);
  return state;
}

test("a mixed diff loads four language packs and a go-only diff does not", async () => {
  const mixed = await promptsFor(diffRepo({
    "app.py": "print(1)\n",
    "app.ts": "export const n = 1;\n",
    "app.go": "package app\n",
    "app.rs": "fn main() {}\n",
  }));
  const code = mixed.prompts[0];
  assert.match(code, /### PY-3 ·/);
  assert.match(code, /### TS-1 ·/);
  assert.match(code, /### GO-1 ·/);
  assert.match(code, /### RS-1 ·/);
  assert.match(code, /### CS-ERR-1 ·/);
  assert.equal(mixed.result.scope.codingStyle.languages.join(","), "python,typescript,go,rust");

  const goOnly = await promptsFor(diffRepo({ "app.go": "package app\n" }));
  assert.match(goOnly.prompts[0], /### GO-1 ·/);
  assert.match(goOnly.prompts[0], /### CS-ERR-1 ·/);
  assert.doesNotMatch(goOnly.prompts[0], /### PY-3 ·/);
  assert.doesNotMatch(goOnly.prompts[0], /### TS-2 ·/);
  assert.doesNotMatch(goOnly.prompts[0], /### RS-1 ·/);
  assert.deepEqual(goOnly.result.scope.codingStyle.languages, ["go"]);
});

test("deleting a rust file does not load the rust pack", async () => {
  const repo = makeRepo();
  commitRel(repo, "lib.rs", "fn old() {}\n", "base");
  const base = sha(repo);
  gitC(repo, ["rm", "lib.rs"]);
  gitC(repo, ["commit", "-m", "delete"]);
  const state = await promptsFor({ repoDir: repo, mode: "diff", base, head: sha(repo), repro: false });
  assert.doesNotMatch(state.prompts[0], /### RS-1 ·/);
  assert.match(state.prompts[2], /### CS-ABS-1 ·/);
  assert.deepEqual(state.result.scope.codingStyle.languages, []);
});

test("shebangs route extensionless scripts and an unknown extension stays on common", async () => {
  const scripts = await promptsFor(diffRepo({
    "bin/pytool": "#!/usr/bin/env python3\nprint(1)\n",
    "bin/jstool": "#!/usr/bin/env node\nconsole.log(1)\n",
  }));
  assert.match(scripts.prompts[0], /### PY-3 ·/);
  assert.match(scripts.prompts[0], /### TS-2 ·/);
  assert.doesNotMatch(scripts.prompts[0], /### TS-1 ·/);
  assert.match(scripts.prompts[0], /TypeScript-only rules are omitted/);

  const notes = await promptsFor(diffRepo({ "notes.md": "hello\n" }));
  assert.match(notes.prompts[0], /### CS-ERR-1 ·/);
  assert.doesNotMatch(notes.prompts[0], /### PY-3 ·|### TS-2 ·|### GO-1 ·|### RS-1 ·/);
  assert.deepEqual(notes.result.scope.codingStyle.languages, []);
});

test("generated Go files are exempt and still named in the prompt", async () => {
  const state = await promptsFor(diffRepo({
    "api/demo.pb.go": "package api\n",
    "hand/gen.go": "// Code generated by protoc. DO NOT EDIT.\npackage hand\n",
  }));
  const generated = state.result.scope.codingStyle.generated;
  assert.ok(generated.includes("api/demo.pb.go"));
  assert.ok(generated.includes("hand/gen.go"));
  assert.match(state.prompts[0], /api\/demo\.pb\.go/);
  assert.match(state.prompts[0], /hand\/gen\.go/);
  assert.match(state.prompts[0], /### GO-1 ·/);
});

test("codingStyle off omits the section and records mode off outside the source manifest", async () => {
  const state = await promptsFor({ ...diffRepo({ "app.ts": "export const n = 1;\n" }), codingStyle: "off" });
  for (const prompt of state.prompts) assert.doesNotMatch(prompt, /## Coding style reference/);
  assert.equal(state.result.scope.codingStyle.mode, "off");
  const manifest = JSON.parse(readFileSync(state.result.scope.manifestPath, "utf8"));
  assert.equal(Object.hasOwn(manifest, "codingStyle"), false);
  assert.equal(state.result.scope.kit.files.some((file) => file.path.startsWith("coding-style/")), false);
});

test("an explicit rust list on a TypeScript diff loads rust and not TypeScript", async () => {
  const state = await promptsFor({ ...diffRepo({ "app.ts": "export const n = 1;\n" }), codingStyle: ["rust"] });
  assert.match(state.prompts[0], /### RS-1 ·/);
  assert.match(state.prompts[0], /### CS-ERR-1 ·/);
  assert.doesNotMatch(state.prompts[0], /### TS-1 ·/);
  assert.doesNotMatch(state.prompts[0], /### TS-2 ·/);
  assert.deepEqual(state.result.scope.codingStyle.languages, ["rust"]);
});

test("strict, empty, and unknown language lists fail before a reviewer or a run directory", async () => {
  const repo = makeRepo();
  for (const codingStyle of ["strict", [], ["java"]]) {
    const runDir = freshRunDir();
    let calls = 0;
    await assert.rejects(
      runReviewGate({ repoDir: repo, mode: "snapshot", paths: ["README.md"], codingStyle, runDir }, rt(async () => { calls += 1; })),
      /codingStyle must be/,
    );
    assert.equal(calls, 0);
    assert.equal(existsSync(runDir), false);
  }
});

test("a frozen style kit ignores a later edit and is not source drift", async () => {
  const root = mkdtempSync(join(tmpdir(), "rgate-style-"));
  const manifest = JSON.parse(readFileSync(join(PACKAGE, "companions.json"), "utf8"));
  for (const rel of manifest.required) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    cpSync(join(ROOT, rel), join(root, rel));
  }
  cpSync(join(ROOT, "coding-style"), join(root, "coding-style"), { recursive: true });
  const rulesPath = join(root, "coding-style", "rules.json");
  const original = readFileSync(rulesPath);
  const args = diffRepo({ "app.py": "print(1)\n" });
  const result = await runReviewGate({ ...args, runDir: freshRunDir() }, {
    ...rt(async (prompt) => {
      writeFileSync(rulesPath, original.toString("utf8").replace("\"version\": 1", "\"version\": 1, \"mutation\": \"MUTATION_SENTINEL\""));
      assert.equal(prompt.includes("MUTATION_SENTINEL"), false);
      return gateReport(prompt.match(/GATE_ID:\s*(\S+)/)[1]);
    }),
    skillsRoot: root,
  });
  assert.equal(result.drift.detected, false);
  const recorded = result.scope.kit.files.find((file) => file.path === "coding-style/rules.json");
  assert.equal(recorded.hash, sha256(original));
  assert.equal(sha256(readFileSync(join(result.artifacts.kitDir, "coding-style/rules.json"))), recorded.hash);
  const manifestJson = JSON.parse(readFileSync(result.scope.manifestPath, "utf8"));
  assert.equal(Object.hasOwn(manifestJson, "codingStyle"), false);

  const again = await runReviewGate({ ...args, runDir: freshRunDir() }, {
    ...rt(async (prompt, opts) => gateReport(opts.label)),
    skillsRoot: root,
  });
  assert.equal(again.scope.manifestHash, result.scope.manifestHash);
  assert.notEqual(again.scope.kit.files.find((file) => file.path === "coding-style/rules.json").hash, recorded.hash);
  rmSync(root, { recursive: true, force: true });
});

test("four language packs stay inside 256 KiB and a huge context still fails first", async () => {
  const args = diffRepo({
    "app.py": "print(1)\n",
    "app.ts": "export const n = 1;\n",
    "app.go": "package app\n",
    "app.rs": "fn main() {}\n",
  });
  const state = await promptsFor(args);
  for (const prompt of state.prompts) assert.ok(Buffer.byteLength(prompt) < 256 * 1024);
  let calls = 0;
  await assert.rejects(
    runReviewGate({ ...args, context: "x".repeat(256 * 1024) }, rt(async () => { calls += 1; })),
    /review prompt exceeds 256 KiB/,
  );
  assert.equal(calls, 0);
});

test("brief keeps strong and some evidence and drops a single-source rule", async () => {
  const state = await promptsFor({ ...diffRepo({ "app.py": "print(1)\n" }), codingStyle: "brief" });
  assert.match(state.prompts[2], /### CS-ABS-1 ·/);
  assert.doesNotMatch(state.prompts[2], /### CS-CMT-3 ·/);
  assert.doesNotMatch(state.prompts[2], /### PY-16 ·/);
  assert.equal(state.result.scope.codingStyle.profile, "brief");
});

test("an enabled ruff selection drops the covered rule and the handoff names it", async () => {
  const bare = await promptsFor(diffRepo({ "app.py": "print(1)\n" }));
  assert.match(bare.prompts[0], /### PY-3 ·/);

  const repo = makeRepo();
  const base = commitRel(repo, "app.py", "print(0)\n", "base");
  writeRel(repo, "pyproject.toml", "[tool.ruff]\nselect = [\"E722\", \"BLE001\", \"S110\"]\n");
  writeRel(repo, "app.py", "print(1)\n");
  gitC(repo, ["add", "-A"]);
  gitC(repo, ["commit", "-m", "head"]);
  const result = await runReviewGate({ repoDir: repo, mode: "diff", base, head: sha(repo), repro: false }, rt(async (prompt, opts) => {
    if (opts.label === "code-review") assert.doesNotMatch(prompt, /### PY-3 ·/);
    assert.match(prompt, /### CS-ERR-2 ·|### CS-ABS-1 ·|### CS-TEST-1 ·/);
    return gateReport(opts.label);
  }));
  const handoff = readFileSync(join(result.artifacts.runDir, "handoff.md"), "utf8");
  assert.match(handoff, /## Lint already covers/);
  assert.match(handoff, /PY-3 \(ruff:E722, ruff:BLE001, ruff:S110\)/);
});
